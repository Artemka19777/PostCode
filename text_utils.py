import re

def clean2(t):
    t = str(t).lower().replace('ё', 'е')
    t = t.split('добавил комментарий')[0]
    for phrase in ['подробное описание возникшей проблемы', 'последовательность действий',
                   'индекс опс', 'номер окна', 'номер телефона для связи с опс',
                   'время возникновения ошибки', 'тема письма', 'инн']:
        t = t.replace(phrase, ' ')
    t = re.sub(r'[^\w\s]|\d+|_', ' ', t)
    return re.sub(r'\s+', ' ', t).strip()